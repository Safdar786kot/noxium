#!/usr/bin/env bash
# Noxium node installer for a fresh Ubuntu/Debian VPS (run as root).
#
#   curl -fsSLO https://raw.githubusercontent.com/<you>/noxium/main/tools/deploy/install-node.sh
#   sudo bash install-node.sh --tarball <URL or path to noxium-linux-x64 tar.gz> [options]
#
# Options:
#   --tarball X       release archive (URL or local file) containing noxiumd       (required)
#   --network N       mainnet (default) | testnet | stagenet
#   --public-rpc      also expose a restricted RPC (for wallets/light clients) on the RPC port
#   --peer HOST:PORT  add a priority peer (repeatable) - use your other seed nodes
#   --prune           prune the blockchain (~1/3 of the disk space)
#   --no-firewall     don't touch ufw
set -euo pipefail

NET=mainnet; TARBALL=""; PUBLIC_RPC=0; PRUNE=0; FIREWALL=1; PEERS=()
while [ $# -gt 0 ]; do
  case "$1" in
    --tarball) TARBALL="$2"; shift 2;;
    --network) NET="$2"; shift 2;;
    --public-rpc) PUBLIC_RPC=1; shift;;
    --peer) PEERS+=("$2"); shift 2;;
    --prune) PRUNE=1; shift;;
    --no-firewall) FIREWALL=0; shift;;
    -h|--help) sed -n 2,16p "$0"; exit 0;;
    *) echo "unknown option $1"; exit 1;;
  esac
done
[ "$(id -u)" = 0 ] || { echo "run as root (sudo)"; exit 1; }
[ -n "$TARBALL" ] || { echo "--tarball is required"; exit 1; }

case "$NET" in
  mainnet)  P2P=17750; RPC=17751; ZMQ=17752; FLAG="";;
  testnet)  P2P=27750; RPC=27751; ZMQ=27752; FLAG="testnet=1";;
  stagenet) P2P=37750; RPC=37751; ZMQ=37752; FLAG="stagenet=1";;
  *) echo "bad --network"; exit 1;;
esac

echo "==> installing packages"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq ca-certificates curl tar ufw libhidapi-libusb0 libusb-1.0-0 libunbound8 libsodium23 \
  libzmq5 libreadline8 libexpat1 libpgm-5.3-0 libprotobuf-lite32 libunwind8 >/dev/null 2>&1 || \
  apt-get install -y -qq ca-certificates curl tar ufw >/dev/null

echo "==> creating user and directories"
id noxium >/dev/null 2>&1 || useradd --system --home-dir /var/lib/noxium --create-home --shell /usr/sbin/nologin noxium
install -d -o noxium -g noxium -m 0750 /var/lib/noxium /var/log/noxium
install -d -m 0755 /opt/noxium /etc/noxium

echo "==> installing binaries"
TMP=$(mktemp -d)
if [[ "$TARBALL" =~ ^https?:// ]]; then curl -fsSL "$TARBALL" -o "$TMP/nox.tar.gz"; else cp "$TARBALL" "$TMP/nox.tar.gz"; fi
tar -xzf "$TMP/nox.tar.gz" -C "$TMP"
BIN=$(dirname "$(find "$TMP" -name noxiumd -type f | head -1)")
[ -x "$BIN/noxiumd" ] || { echo "noxiumd not found in archive"; exit 1; }
install -m 0755 "$BIN"/noxium* /opt/noxium/
ln -sf /opt/noxium/noxiumd /usr/local/bin/noxiumd
for b in /opt/noxium/noxium-wallet-*; do ln -sf "$b" /usr/local/bin/; done
rm -rf "$TMP"
/opt/noxium/noxiumd --version

echo "==> writing /etc/noxium/noxiumd.conf"
{
  echo "# generated by install-node.sh ($NET)"
  [ -n "$FLAG" ] && echo "$FLAG"
  echo "data-dir=/var/lib/noxium"
  echo "log-file=/var/log/noxium/noxiumd.log"
  echo "log-level=0"
  echo "max-log-file-size=104857600"
  echo "p2p-bind-ip=0.0.0.0"
  echo "p2p-bind-port=$P2P"
  echo "zmq-rpc-bind-port=$ZMQ"
  echo "no-igd=1"
  echo "out-peers=32"
  echo "in-peers=128"
  echo "enable-dns-blocklist=0"
  echo "db-sync-mode=safe"
  [ "$PRUNE" = 1 ] && echo "prune-blockchain=1"
  for p in "${PEERS[@]}"; do echo "add-priority-node=$p"; done
  if [ "$PUBLIC_RPC" = 1 ]; then
    echo "rpc-bind-ip=0.0.0.0"
    echo "rpc-bind-port=$RPC"
    echo "restricted-rpc=1"
    echo "confirm-external-bind=1"
    echo "rpc-ssl=autodetect"
    echo "public-node=1"
    echo "rpc-max-connections-per-public-ip=10"
  else
    echo "rpc-bind-ip=127.0.0.1"
    echo "rpc-bind-port=$RPC"
  fi
} > /etc/noxium/noxiumd.conf

echo "==> installing systemd service"
cat > /etc/systemd/system/noxiumd.service <<UNIT
[Unit]
Description=Noxium daemon ($NET)
After=network-online.target
Wants=network-online.target

[Service]
User=noxium
Group=noxium
Type=simple
ExecStart=/opt/noxium/noxiumd --config-file /etc/noxium/noxiumd.conf --non-interactive
Restart=always
RestartSec=10
TimeoutStopSec=120
LimitNOFILE=65536
# hardening
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=strict
ProtectHome=true
ReadWritePaths=/var/lib/noxium /var/log/noxium

[Install]
WantedBy=multi-user.target
UNIT
systemctl daemon-reload
systemctl enable --now noxiumd

if [ "$FIREWALL" = 1 ]; then
  echo "==> firewall"
  ufw allow OpenSSH >/dev/null
  ufw allow "$P2P"/tcp comment "noxium p2p" >/dev/null
  [ "$PUBLIC_RPC" = 1 ] && ufw allow "$RPC"/tcp comment "noxium restricted rpc" >/dev/null
  ufw --force enable >/dev/null
fi

IP=$(curl -fsS4 --max-time 5 https://api.ipify.org 2>/dev/null || hostname -I | awk '{print $1}')
cat <<DONE

Noxium node installed and running ($NET).
  status:    systemctl status noxiumd
  logs:      tail -f /var/log/noxium/noxiumd.log
  sync info: curl -s http://127.0.0.1:$RPC/get_info
  this node as a seed:  $IP:$P2P
DONE
